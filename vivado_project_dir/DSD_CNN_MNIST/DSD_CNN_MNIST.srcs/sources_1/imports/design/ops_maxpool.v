//////////////// AGU CODE BEGIN ////////////////

    always @(*) begin
        
        
        // Defaults to prevent latches:
        h_in_next                = h_in;
        w_in_next                = w_in;
        h_out_next               = h_out;
        w_out_next               = w_out;
        c_in_next                = c_in;
        c_out_next               = c_out;
        win_start_addr_next      = win_start_addr;
        win_row_start_addr_next  = win_row_start_addr;
        win_complete_flag        = 1'b0;
        fmap_compute_almost_done = 1'b0;
        win_base_addr_next       = win_base_addr;
        fmap_row_start_addr_next = fmap_row_start_addr;
        channel_start_addr_next  = channel_start_addr;

        // Only advance pointers if FSM is actively running the pipeline
        if (state_curr == FILL || state_curr == COMPUTE) begin
            
            if (w_in == POOL_KERNEL_SIZE - 1) begin
                w_in_next = 0; 
                
                if (h_in == POOL_KERNEL_SIZE - 1) begin
                    h_in_next = 0; 
                    win_complete_flag = 1'b1;
                    
                    // FMAP SLIDING LOGIC 
                    if (w_out == OUT_FMAP_DIM_W - 1) begin
                        w_out_next = 0; 
                        
                        if (h_out == OUT_FMAP_DIM_H - 1) begin
                            h_out_next = 0; 
                            
                            if (c_out == OUT_FMAP_DIM_C - 1) begin
                                fmap_compute_almost_done = 1'b1; 
                            end else begin
                                // Jump to Next Channel
                                c_out_next = c_out + 1;
                                c_in_next  = c_in + 1;
                                
                                // Advance the channel anchor
                                channel_start_addr_next  = channel_start_addr + inside_fmap_channel_offset;
                                
                                // Reset all other anchors to the new channel start
                                fmap_row_start_addr_next = channel_start_addr_next;
                                win_base_addr_next       = channel_start_addr_next;
                                win_row_start_addr_next  = channel_start_addr_next;
                                win_start_addr_next      = channel_start_addr_next;
                            end
                        end else begin
                            // Jump to Next Row of Windows
                            h_out_next = h_out + 1;
                            
                            // Advance the FMAP row anchor (using the offset calculated in IDLE)
                            fmap_row_start_addr_next = fmap_row_start_addr + row_jump_offset;
                            
                            // Reset window anchors to the start of this new row
                            win_base_addr_next       = fmap_row_start_addr_next;
                            win_row_start_addr_next  = fmap_row_start_addr_next;
                            win_start_addr_next      = fmap_row_start_addr_next;
                        end
                    end else begin
                        // Slide Window Right
                        w_out_next = w_out + 1;
                        
                        // Advance the window anchor right by the pool size
                        win_base_addr_next       = win_base_addr + POOL_KERNEL_SIZE;
                        
                        // Reset the reading pointers to this new window anchor
                        win_row_start_addr_next  = win_base_addr_next;
                        win_start_addr_next      = win_base_addr_next;
                    end
                end else begin
                    // Move down 1 row INSIDE the current window
                    h_in_next = h_in + 1;
                    win_row_start_addr_next = win_row_start_addr + IN_FMAP_DIM_W;
                    win_start_addr_next     = win_row_start_addr + IN_FMAP_DIM_W;
                end
            end else begin
                // Move right 1 pixel INSIDE the current window
                w_in_next = w_in + 1;
                win_start_addr_next = win_start_addr + 1;
            end
        end
    end
    //////////////// AGU CODE END   ////////////////

endmodule